-- PROPOSAL ONLY. Not applied to Supabase.
-- Reviewed read-only against current public player_career_stats/player_accolades schema.
-- Run in isolated PostgreSQL before seeking founder approval.
-- Purpose: career-summary-first storage, no individual season rows.
BEGIN;
CREATE TABLE public.player_playoff_career_stats (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id bigint NOT NULL UNIQUE REFERENCES public.players(id) ON DELETE CASCADE,
  games_played integer NOT NULL CHECK (games_played > 0),
  postseasons_played integer CHECK (postseasons_played > 0),
  points_total bigint CHECK (points_total >= 0),
  rebounds_total bigint CHECK (rebounds_total >= 0),
  assists_total bigint CHECK (assists_total >= 0),
  steals_total bigint CHECK (steals_total >= 0),
  blocks_total bigint CHECK (blocks_total >= 0),
  field_goals_made bigint CHECK (field_goals_made >= 0),
  field_goals_attempted bigint CHECK (field_goals_attempted >= field_goals_made),
  career_ppg numeric,
  career_rpg numeric,
  career_apg numeric,
  career_spg numeric,
  career_bpg numeric,
  career_fg_pct numeric CHECK (career_fg_pct BETWEEN 0 AND 1),
  primary_source text,
  secondary_source text,
  source_cutoff text NOT NULL,
  verification_status text NOT NULL DEFAULT 'unverified'
    CHECK (verification_status IN ('unverified','single_source','cross_checked','needs_fallback_cross_check','conflict_review')),
  verified_at timestamptz,
  verification_notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.player_playoff_career_stats ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Public can read player playoff career stats"
  ON public.player_playoff_career_stats
  FOR SELECT TO anon, authenticated USING (true);
GRANT SELECT ON public.player_playoff_career_stats TO anon, authenticated;
-- No INSERT, UPDATE, or DELETE grants to anon/authenticated.
-- Existing player_accolades_unique_idx already prevents duplicate event keys
-- using COALESCE(result,''), COALESCE(season_year,0), COALESCE(team,'').
-- Do not create a redundant or incompatible unique constraint.
COMMIT;
