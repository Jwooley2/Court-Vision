-- Supabase's built-in public roles do not exist in plain PostgreSQL containers.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
-- Recreate relevant preexisting production index and columns in isolated PostgreSQL.
CREATE TABLE public.players (
  id bigint PRIMARY KEY, external_id text, name text
);
CREATE TABLE public.player_accolades (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id bigint NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
  league text NOT NULL DEFAULT 'NBA',
  accolade_type text NOT NULL,
  accolade_name text NOT NULL,
  result text,
  season_year integer,
  team text
);
CREATE UNIQUE INDEX player_accolades_unique_idx ON public.player_accolades
  (player_id,league,accolade_name,COALESCE(result,''),COALESCE(season_year,0),COALESCE(team,''));
